// Development only: run with TypeScript on NODE_PATH, or SAE_TYPESCRIPT pointing to it.
// No parser, dynamic evaluation or source-code deserialization runs in the browser.
const ts = require(process.env.SAE_TYPESCRIPT || 'typescript');
const fs = require('node:fs');
const files = ['utils','memory','autoconf','expansion','events','gayle','ide','filesys','hardfile','dongle','input','serpar','custom','blitter','copper','playfield','audio','cia','disk','rtc','m68k','cpu'];
const check = process.argv.includes('--check');
// Explicit exclusions: host resources/timing and tables rebuilt by setup.
// All remaining constructor-scoped mutable variables are part of the state schema.
const omit = {
  SAEO_Audio: ['driver','cache','scale','muted','paused','have_sound','sound_available'],
  SAEO_Joystick: ['requestID'],
  SAEO_M68K: ['prevtime'],
  SAEO_CPU: ['iTab','ccTab','exEAtab','ldEA8tab','stEA8tab','ldEA16tab','stEA16tab','ldEA32tab','stEA32tab','regs_da','inst_mn'],
  SAEO_Events: ['ma_frameskipt','ma_reflowt','fps_mavg','idle_mavg','frametime','lastframetime','idletime','vsyncmintime','vsyncmaxtime','vsyncwaittime','is_syncline','is_syncline_end']
};
function write(path, source) {
  if (check) {
    if (fs.readFileSync(path, 'utf8') !== source) throw Error(path + ': regenerate state accessors');
  } else fs.writeFileSync(path, source);
}
function names(fields, indent) {
  const lines = []; let line = '';
  for (const field of fields) {
    if (line && line.length + field.length > 96) { lines.push(indent + line); line = ''; }
    line += field + ',';
  }
  if (line) lines.push(indent + line);
  return lines.join('\n');
}
const globals = [];
for (const file of files) {
  let source = fs.readFileSync('sae/' + file + '.js', 'utf8')
    .replace(/\n\t\/\/ BEGIN GENERATED STATE ACCESS[\s\S]*?\t\/\/ END GENERATED STATE ACCESS\n/g, '');
  const ast = ts.createSourceFile(file, source, ts.ScriptTarget.Latest, true, ts.ScriptKind.JS);
  const edits = [];
  for (const node of ast.statements) {
    if (ts.isVariableStatement(node)) for (const d of node.declarationList.declarations) {
      if (/^(SAEV|SAER)_/.test(d.name.text)) globals.push(d.name.text);
    }
    if (!ts.isFunctionDeclaration(node) || !/^SAEO_/.test(node.name.text)) continue;
    const variables = new Set(), functions = [], constants = [];
    function visit(child) {
      if (ts.isFunctionLike(child)) {
        if (ts.isFunctionDeclaration(child) && child.name) functions.push(child.name.text);
        return; // Never include stack-local variables from methods/callbacks.
      }
      if (ts.isVariableDeclarationList(child) && !(child.flags & ts.NodeFlags.Const)) {
        for (const d of child.declarations) if (ts.isIdentifier(d.name)) variables.add(d.name.text);
      }
      ts.forEachChild(child, visit);
    }
    ts.forEachChild(node.body, visit);
    if (!variables.size && !functions.length && node.name.text !== 'SAEO_Devices') continue;
    // Constant object/array identities matter (e.g. blitter cycle diagrams).
    for (const statement of node.body.statements) {
      if (ts.isVariableStatement(statement) && (statement.declarationList.flags & ts.NodeFlags.Const)) {
        for (const d of statement.declarationList.declarations) if (ts.isIdentifier(d.name)) constants.push(d.name.text);
      }
    }
    const fields = [...variables].filter(key => !(omit[node.name.text] || []).includes(key));
    const code = '\n\t// BEGIN GENERATED STATE ACCESS — tools/generate-state-access.cjs\n' +
      '\tObject.defineProperty(this, "_saeState", {value: {\n' +
      '\t\tget: function() { return {\n' + names(fields, '\t\t\t') + '\n\t\t}; },\n' +
      '\t\tset: function(s) {\n' + fields.map(key => '\t\t\t' + key + '=s.' + key + ';').join('\n') + '\n\t\t},\n' +
      '\t\tfunctions: function() { return {\n' + names(functions, '\t\t\t') + '\n\t\t}; },\n' +
      '\t\tconstants: function() { return {\n' + names(constants, '\t\t\t') + '\n\t\t}; }\n' +
      '\t}});\n\t// END GENERATED STATE ACCESS\n';
    edits.push({position: node.body.end - 1, code});
  }
  for (const edit of edits.reverse()) source = source.slice(0, edit.position) + edit.code + source.slice(edit.position);
  write('sae/' + file + '.js', source);
}
globals.push('SAEV_spcflags');
const build = require('node:crypto').createHash('sha256');
for (const file of [...files,'amiga','state','config','video','prototypes','roms']) build.update(fs.readFileSync('sae/' + file + '.js'));
write('sae/state-globals.js', '// Generated by tools/generate-state-access.cjs.\nvar SAEStateGlobals = {\n' +
  ' build: ' + JSON.stringify(build.digest('hex')) + ',\n' +
  ' get: function() { return {\n' + names(globals, '  ') + '\n }; },\n' +
  ' set: function(s) {\n' + globals.map(key => '  ' + key + '=s.' + key + ';').join('\n') + '\n }\n};\n');
